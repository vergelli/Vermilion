return function(H)
  local function ok(cond, msg) if not cond then error(msg, 2) end end
  local G, M, DT = Vermilion.Graph, Vermilion.Metrics, Vermilion.DebuffTracker

  M.reset()
  Vermilion.Visibility.set("graph", true)
  G.on_flush_click()
  G.on_record_click()
  H.advance(20000)
  ok(M.fight_ms() == 0, "no hit, no fight")
  H.damage_out({ hit = 1000, ability_id = 31 })
  H.advance(10000)
  H.damage_out({ hit = 1000, ability_id = 31 })
  ok(M.fight_ms() == 10000, "the fight runs from the first hit to the last, got " .. M.fight_ms())
  H.advance(30000)
  G.on_stop_click()
  ok(M.fight_ms() == 10000, "waiting before and after the fight changes nothing")
  local sm = G.export_summary()
  ok(sm.avg == 200, "two thousand over ten seconds, got " .. tostring(sm.avg))

  local sess = Vermilion.SessionStore.capture()
  ok(sess.head.sum.fight_ms == 10000, "the session keeps its fight time")
  G.on_flush_click()
  ok(M.fight_ms() == 0, "flush forgets it")
  ok(G.load_session(sess), "the session reloads")
  ok(M.fight_ms() == 10000, "and loading brings it back")
  ok(M.session_avg(sess.head.sum) == 200, "the library reads the same average")
  ok(G.export_summary().avg == 200, "so does the header")
  sess.head.sum.fight_ms = nil
  ok(M.session_avg(sess.head.sum) == sess.head.sum.avg, "an older session keeps the average it saved")

  local rec = { uptime_ms = 5000 }
  ok(DT.uptime_of(rec) == 0.5, "debuff uptime divides by the fight, got " .. DT.uptime_of(rec))
  rec.uptime_ms = 15000
  ok(DT.uptime_of(rec) == 1, "and never passes one hundred percent")

  G.on_flush_click()
  G.on_record_click()
  H.res_power(POWERTYPE_MAGICKA, 30000, 30000)
  H.res_power(POWERTYPE_STAMINA, 30000, 30000)
  H.advance(10000)
  H.damage_out({ hit = 1000, ability_id = 31 })
  H.res_power(POWERTYPE_MAGICKA, 0, 30000)
  H.advance(5000)
  H.res_power(POWERTYPE_MAGICKA, 30000, 30000)
  H.advance(5000)
  H.damage_out({ hit = 1000, ability_id = 31 })
  H.advance(10000)
  G.on_stop_click()
  local rs = Vermilion.Resources.summary(Vermilion.TemporalBuffer)
  ok(rs.mag_low_pct > 0.4 and rs.mag_low_pct < 0.6, "an empty pool counts as low, over the fight only, got " .. rs.mag_low_pct)
  ok(rs.sta_low_pct == 0, "a full pool is not low")
  local saved = Vermilion.SessionStore.capture()
  ok(saved.head.sum.fight_t0 and saved.head.sum.fight_t0 >= 9000 and saved.head.sum.fight_t0 <= 11000, "the session keeps where the fight starts, got " .. tostring(saved.head.sum.fight_t0))
  G.on_flush_click()
  ok(G.load_session(saved), "the session reloads")
  local rs2 = Vermilion.Resources.summary(Vermilion.TemporalBuffer)
  ok(math.abs(rs2.mag_low_pct - rs.mag_low_pct) < 0.11, "a reloaded session reads the same, got " .. rs2.mag_low_pct .. " and " .. rs.mag_low_pct)

  G.on_flush_click()
  G.on_record_click()
  H.damage_out({ hit = 1000, ability_id = 31 })
  H.kill({ result = ACTION_RESULT_DIED, target_unit_id = 901 })
  ok(Vermilion.Kills.count() == 1, "a kill with no experience counts, got " .. Vermilion.Kills.count())
  H.advance(1000)
  G.on_stop_click()

  G.on_flush_click()
  Vermilion.Visibility.set("graph", false)
  M.reset()
end
